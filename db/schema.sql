-- MedPredict server-only Supabase schema. Not exposed through the browser Data API.
-- Run as the project database administrator; deploy before setting DATABASE_URL.
BEGIN;
CREATE SCHEMA IF NOT EXISTS medpredict;
REVOKE ALL ON SCHEMA medpredict FROM PUBLIC, anon, authenticated;
CREATE TABLE IF NOT EXISTS medpredict.users (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 email TEXT NOT NULL UNIQUE, name TEXT, username TEXT UNIQUE, password_hash TEXT,
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS medpredict.health_assessments (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id BIGINT NOT NULL REFERENCES medpredict.users(id) ON DELETE CASCADE,
 disease TEXT NOT NULL, input_data TEXT, prediction TEXT, probability DOUBLE PRECISION,
 evaluation TEXT, created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS medpredict.family_connections (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 owner_user_id BIGINT NOT NULL REFERENCES medpredict.users(id) ON DELETE CASCADE,
 member_user_id BIGINT NOT NULL REFERENCES medpredict.users(id) ON DELETE CASCADE,
 relationship TEXT NOT NULL, status TEXT NOT NULL DEFAULT 'pending' CHECK(status IN ('pending','accepted')),
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE(owner_user_id,member_user_id), CHECK(owner_user_id <> member_user_id)
);
CREATE TABLE IF NOT EXISTS medpredict.reviews (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id BIGINT NOT NULL UNIQUE REFERENCES medpredict.users(id) ON DELETE CASCADE,
 display_name TEXT NOT NULL CHECK(length(display_name) BETWEEN 2 AND 60),
 rating INTEGER NOT NULL CHECK(rating BETWEEN 1 AND 5),
 title TEXT NOT NULL CHECK(length(title) BETWEEN 3 AND 100),
 comment TEXT NOT NULL CHECK(length(comment) BETWEEN 10 AND 1500),
 context TEXT NOT NULL CHECK(length(context) BETWEEN 1 AND 80),
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS medpredict.workspace_items (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id BIGINT NOT NULL REFERENCES medpredict.users(id) ON DELETE CASCADE,
 kind TEXT NOT NULL,title TEXT NOT NULL,payload TEXT NOT NULL,
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS medpredict.user_preferences (
 user_id BIGINT PRIMARY KEY REFERENCES medpredict.users(id) ON DELETE CASCADE,
 language TEXT NOT NULL DEFAULT 'en',theme TEXT NOT NULL DEFAULT 'light' CHECK(theme IN ('light','dark'))
);
CREATE INDEX IF NOT EXISTS workspace_user_date ON medpredict.workspace_items(user_id,created_at);
CREATE INDEX IF NOT EXISTS assessments_user_date ON medpredict.health_assessments(user_id,created_at);
CREATE INDEX IF NOT EXISTS family_member ON medpredict.family_connections(member_user_id);
CREATE INDEX IF NOT EXISTS reviews_date ON medpredict.reviews(updated_at);
-- Defence in depth: the API roles have neither schema access nor table access.
ALTER TABLE medpredict.users ENABLE ROW LEVEL SECURITY;
ALTER TABLE medpredict.health_assessments ENABLE ROW LEVEL SECURITY;
ALTER TABLE medpredict.family_connections ENABLE ROW LEVEL SECURITY;
ALTER TABLE medpredict.reviews ENABLE ROW LEVEL SECURITY;
ALTER TABLE medpredict.workspace_items ENABLE ROW LEVEL SECURITY;
ALTER TABLE medpredict.user_preferences ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON ALL TABLES IN SCHEMA medpredict FROM PUBLIC,anon,authenticated;
REVOKE ALL ON ALL SEQUENCES IN SCHEMA medpredict FROM PUBLIC,anon,authenticated;
COMMIT;
